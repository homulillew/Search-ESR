"""Validate and seal manually recorded masked reviews before any unmask."""
import argparse
from ..common import *
def seal(stage):
    packets=read(P/stage/'review/PACKETS.json');parts=sorted((P/stage/'review').glob('PART_*.json'))
    labels=[x for p in parts for x in read(p)];assert len(labels)==len(packets)
    byid={p['review_id']:p for p in packets};assert len(byid)==len(labels)
    refs=read(P/'e0_reference/REFERENCE_TASK_STRUCTURE.json');cases=bank(stage)
    qmap={c['question']:q for q,c in cases.items()};seen=set()
    for r in labels:
        rid=r['review_id'];assert rid not in seen;seen.add(rid);packet=byid[rid];ref=refs[qmap[packet['question']]]
        assert set(r['coverage'])=={x['id'] for x in ref['material_units']}
        assert set(r['coverage_nodes'])==set(r['coverage'])
        assert all(type(v) is bool for v in r['coverage'].values())
        for m,ns in r['coverage_nodes'].items():
            assert all(type(n) is int and 1<=n<=len(packet['candidate_task_units']) for n in ns)
            assert not r['coverage'][m] or ns
        assert set(r['dependency'])=={x['id'] for x in ref['dependency_checkpoints']}
        for e in r['critical_violations']:
            assert e['invariant'] in {x['id'] for x in ref['critical_invariants']}
            assert e['reason'] and e['types']
        assert r['reason'] and r['ambiguity'] in ('low','medium','high')
        for k in ('severe_broadness','severe_fragmentation','harmful_merge','harmful_split'):assert type(r[k]) is bool
    write(P/stage/'review/FIRST_PASS.json',sorted(labels,key=lambda x:x['review_id']))
    write(P/stage/'review/FIRST_PASS_ATTESTATION.md',f'''# First-pass review seal

{len(labels)} planned responses reviewed against the frozen Q-only reference.
The semantic judgments are explicit single-Codex-reviewer annotations.
Packets contain only Q and normalized candidate task units; reference constraints
are known. Arm, replicate, raw source anchors, provider reasoning and aggregate
results were not inspected during this pass. Extractive style may disclose the
representation; this is partial masking, not independent double-blind review.

No gold answer, Claims, old Dynamic-O review or future tool output was consulted.
Missing/partial units and uncertainty are recorded. First-pass labels must be
committed before opening KEY or second-pass provenance. No semantic labels are
generated by a keyword/lexical classifier. No reference revisions occurred.

Packet SHA256: {sha(P/stage/'review/PACKETS.json')}
Reference SHA256: {sha(P/'e0_reference/REFERENCE_TASK_STRUCTURE.json')}
First-pass SHA256: {sha(P/stage/'review/FIRST_PASS.json')}
''')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('stage',choices=STAGES);seal(p.parse_args().stage)
