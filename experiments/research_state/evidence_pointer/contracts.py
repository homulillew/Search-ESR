"""Evidence Pointer State v0 contracts.

Deterministic-first rule: anything the harness can recover from the Observation,
the attempt log or program state must not be re-generated by a model.

The reviewer (a human or a future selector) only ever outputs *addresses*:

    {"pointers": [{"window_ref": <visible window>, "start": int, "end": int}]}

The harness materializes the exact text, the docid, the document hash, the
relative and absolute character ranges, the URL and the attempt binding by
Python slicing. No model and no reviewer ever prints source text or provenance.

Quote membership is not a concept here: there is no quote to copy, therefore no
ref truncation, no whitespace normalisation, no ellipsis join and no smart-quote
substitution can occur. This module deliberately does not import a JSON schema
for paraphrase.
"""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json

VERSION = 'evidence_pointer_v0'
STAGE = 'evidence_pointer'
MAX_POINTERS = 2
MAX_WINDOWS = 10

_POINTER_FIELDS = ('window_ref', 'start', 'end')
_STATE_FIELDS = ('evidence_id', 'attempt_id', 'window_ref', 'docid',
                 'document_sha256', 'url', 'relative_start', 'relative_end',
                 'absolute_start', 'absolute_end', 'text')


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':'), allow_nan=False)


def digest(value):
    return hashlib.sha256(canonical(value).encode('utf-8')).hexdigest()


def _pairs(pairs):
    value = {}
    for key, child in pairs:
        if key in value:
            raise ValueError('Duplicate JSON key')
        value[key] = child
    return value


def _constant(value):
    raise ValueError('Non-finite JSON number')


def loads(text):
    return json.loads(text, object_pairs_hook=_pairs, parse_constant=_constant)


def seal(value):
    value = deepcopy(value)
    if 'sha256' in value:
        raise ValueError('Already sealed')
    return {**value, 'sha256': digest(value)}


def verify(value):
    if not isinstance(value, dict) or value.get('sha256') != digest(
            {k: v for k, v in value.items() if k != 'sha256'}):
        raise ValueError('Artifact hash mismatch')
    return value


def nonempty(value, maximum=16000):
    if not isinstance(value, str) or not value.strip() or len(value) > maximum:
        raise ValueError('Expected bounded nonempty text')
    return value


def _span(value, length):
    """An address into a window body. bool is not int; no negatives, no reversal."""
    if type(value) is not int or isinstance(value, bool):
        raise ValueError('Span bound must be a plain integer, not bool or float')
    if value < 0:
        raise ValueError('Negative span bound')
    if value > length:
        raise ValueError('Span bound outside this window body')
    return value


def windows(observation):
    """Re-check window identities at every binding; provenance is never cached."""
    if not isinstance(observation, list) or not observation or len(observation) > MAX_WINDOWS:
        raise ValueError('Observation must be a nonempty list of at most ten windows')
    refs = {}
    for item in observation:
        if not isinstance(item, dict):
            raise ValueError('Invalid window')
        for key in ('window_ref', 'docid', 'document_sha256'):
            nonempty(item.get(key), 4000)
        if not isinstance(item.get('url'), str):
            raise ValueError('Source URL must remain text, possibly empty')
        body = item.get('text')
        start, end = item.get('offset'), item.get('end_char')
        if (not isinstance(body, str) or type(start) is not int or type(end) is not int
                or start < 0 or end < start or end - start != len(body)):
            raise ValueError('Window body and character range differ')
        if len(item['document_sha256']) != 64 or any(
                c not in '0123456789abcdef' for c in item['document_sha256']):
            raise ValueError('Invalid document version')
        if item['window_ref'] in refs:
            raise ValueError('Duplicate window in a single search result')
        refs[item['window_ref']] = item
    return refs


def check_pointer_selection(selection, value):
    """Validate the reviewer's addresses against the frozen observation.

    `selection` is the frozen collection case; `value` is the reviewer artifact.
    The reviewer may record a rationale, but it is never part of a pointer and is
    never materialized into model input.
    """
    verify(value)
    if set(value) - {'pointers', 'rationale', 'sha256'}:
        raise ValueError('Reviewer artifact has undeclared fields')
    pointers = value.get('pointers')
    if pointers is None:
        # An explicit empty evidence state is a legal, meaningful observation.
        return {'pointers': [], 'rationale': value.get('rationale')}
    if not isinstance(pointers, list) or len(pointers) > MAX_POINTERS:
        raise ValueError(f'Select at most {MAX_POINTERS} pointers per case')
    refs = windows(selection['observation'])
    seen = set()
    kept = []
    for pointer in pointers:
        if not isinstance(pointer, dict) or set(pointer) != set(_POINTER_FIELDS):
            raise ValueError('A pointer is exactly window_ref + start + end')
        ref = nonempty(pointer['window_ref'], 4000)
        if ref not in refs:
            raise ValueError('Pointer addresses a window that is not visible here')
        body = refs[ref]['text']
        start = _span(pointer['start'], len(body))
        end = _span(pointer['end'], len(body))
        if end <= start:
            raise ValueError('Pointer range is empty or reversed')
        key = (ref, start, end)
        if key in seen:
            raise ValueError('Duplicate pointer')
        seen.add(key)
        # A pointer cannot cross a window: it addresses exactly one window body.
        kept.append({'window_ref': ref, 'start': start, 'end': end})
    return {'pointers': kept, 'rationale': value.get('rationale')}


def attempt_id(case_id):
    """Harness-assigned attempt identity. q0 is the verbatim question (A0)."""
    if not isinstance(case_id, str) or not case_id.strip():
        raise ValueError('Case identity must be text')
    return 'A0:' + case_id


def materialize(pointer, window, case_id, index):
    """Recover exact source text and full provenance by Python slicing.

    Nothing in the returned object comes from the reviewer except the address.
    """
    refs = windows([window])
    ref = pointer['window_ref']
    body = refs[ref]['text']
    start, end = _span(pointer['start'], len(body)), _span(pointer['end'], len(body))
    if end <= start:
        raise ValueError('Empty pointer range')
    absolute_start = window['offset'] + start
    absolute_end = window['offset'] + end
    if absolute_start != window['offset'] + start or absolute_end > window['end_char']:
        raise ValueError('Absolute range escapes the source window')
    return {
        'evidence_id': f'E{index + 1}',
        'attempt_id': attempt_id(case_id),
        'window_ref': ref,
        'docid': window['docid'],
        'document_sha256': window['document_sha256'],
        'url': window['url'],
        'relative_start': start,
        'relative_end': end,
        'absolute_start': absolute_start,
        'absolute_end': absolute_end,
        # Deterministic recovery, character for character. Never a copy.
        'text': body[start:end],
    }


def check_evidence(evidence, observation):
    """Prove a materialized pointer still resolves to the same source bytes.

    With `observation=None` only the object shape is checked; that form is used
    when a caller must reject a malformed evidence object without a window set.
    """
    if not isinstance(evidence, dict) or set(evidence) != set(_STATE_FIELDS):
        raise ValueError('Evidence object has the wrong shape')
    if not evidence['evidence_id'].startswith('E') or not evidence['evidence_id'][1:].isdecimal():
        raise ValueError('Evidence identity must be harness-assigned')
    case_id = evidence['attempt_id'].split(':', 1)
    if len(case_id) != 2 or case_id[0] != 'A0' or not case_id[1].strip():
        raise ValueError('Attempt binding must be A0:<case>')
    if observation is None:
        return evidence
    refs = windows(observation)
    window = refs.get(evidence['window_ref'])
    if window is None:
        raise ValueError('Pointer source window disappeared')
    if evidence['docid'] != window['docid']:
        raise ValueError('Document identity changed after the pointer was frozen')
    if evidence['document_sha256'] != window['document_sha256']:
        raise ValueError('Document hash changed after the pointer was frozen')
    body = window['text']
    start, end = evidence['relative_start'], evidence['relative_end']
    if not (0 <= start < end <= len(body)):
        raise ValueError('Pointer range no longer inside the window body')
    if (evidence['absolute_start'] != window['offset'] + start
            or evidence['absolute_end'] != window['offset'] + end):
        raise ValueError('Window offset changed after the pointer was frozen')
    if evidence['text'] != body[start:end]:
        raise ValueError('Recovered text differs from the materialized text')
    if evidence['url'] != window['url']:
        raise ValueError('Source URL changed after the pointer was frozen')
    return evidence


def state_message(evidence, observation=None):
    """The ONLY form in which evidence reaches a model.

    Derived fields only. Reviewer rationale, labels, outcomes, gold answers and
    any future trajectory are structurally absent.
    """
    if not isinstance(evidence, list):
        raise ValueError('Evidence state must be a list')
    for item in evidence:
        check_evidence(item, observation)
    return {'kind': 'evidence_pointer_state', 'evidence': deepcopy(evidence)}


def show_window(window, width=100):
    """Reviewer annotation helper: print a window body with character offsets.

    A pure UI convenience. It never alters the source text and is not part of the
    state, the plan or any model request.
    """
    refs = windows([window])
    body = refs[window['window_ref']]['text']
    lines = []
    for begin in range(0, len(body), width):
        end = min(begin + width, len(body))
        lines.append(f'char {begin}:{end}\n{body[begin:end]}')
    return '\n'.join(lines)
